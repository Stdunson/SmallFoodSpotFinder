import re

# Generate URL-friendly versions of franchise names
big_franchises_url = {
    re.sub(r"[^a-z0-9]+", "-", name.lower().replace("&", "and").replace("'", "")).strip("-")
    for name in big_franchises
}

def determine_locality(place) -> bool:
    """
    Scoring system:
    - Strong signals: +2 points
    - Moderate signals: +1 point
    - Threshold: 2+ points = local/regional restaurant
 
    True if restaurant appears to be local, False if likely a chain/franchise
    """
    score = 0
    
    # Extract name - handle both string and dict formats from Google API
    if isinstance(place.name, dict):
        place_name = place.name.get('text', '')
    else:
        place_name = place.name or ""
    
    # Check if restaurant name contains any chain name
    place_name_lower = place_name.lower() if place_name else ""
    is_name_chain = any(
        chain_url in place_name_lower.replace("&", "and").replace("'", "").replace(" ", "-")
        for chain_url in big_franchises_url
    ) or any(
        chain.lower() in place_name_lower for chain in big_franchises
    )
    
    # Strong signal: No website domain (local businesses often lack online presence)
    if not place.websiteUri:
        score += 2
    else:
        # Strong signal: Has website but not a chain domain
        url_lower = place.websiteUri.lower()
        is_chain_domain = any(chain_url in url_lower for chain_url in big_franchises_url)
        
        if not is_chain_domain and "/locations/" not in url_lower:
            score += 2
    
    # Strong signal: Few reviews (less than 200) = likely not a major chain
    if place.userRatingCount is not None:
        if place.userRatingCount < 200:
            score += 2
        elif place.userRatingCount < 500:
            score += 1
    
    # Moderate signal: Very high rating with low count (local favorite)
    if place.rating is not None and place.rating > 4.5:
        if place.userRatingCount is not None and place.userRatingCount < 100:
            score += 2
        else:
            score += 1
    
    # Moderate signal: Cash only (local businesses more likely)
    if hasattr(place, 'paymentOptions') and place.paymentOptions:
        if hasattr(place.paymentOptions, 'acceptsCashOnly') and place.paymentOptions.acceptsCashOnly:
            score += 2
    
    # Moderate signal: Fine dining or expensive (less likely to be chain)
    if place.priceLevel is not None:
        if place.priceLevel in ["PRICE_LEVEL_EXPENSIVE", "PRICE_LEVEL_VERY_EXPENSIVE"]:
            score += 1
    
    # Reduce score if name contains chain name
    if is_name_chain:
        score -= 3
    
    logger.debug(f"Locality score for '{place_name}': {score} (chain={is_name_chain})")
    return score >= 2